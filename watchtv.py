#!/usr/bin/env python3
import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

__version__ = "0.9.0"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Temporarily stream media to your Smart TV via MiniDLNA or Google Chromecast with subtitle support."
    )
    parser.add_argument(
        "--version",
        "-v",
        action="version",
        version=f"%(prog)s {__version__}",
    )
    parser.add_argument(
        "--media",
        "--media-folder",
        "-m",
        dest="media",
        required=True,
        type=str,
        help="Path to a movie file or a folder containing movies.",
    )
    parser.add_argument(
        "--name",
        "-n",
        default="mac-movies",
        type=str,
        help="Friendly server name shown on the TV (default: 'mac-movies').",
    )
    parser.add_argument(
        "--interface",
        "-i",
        default="en0",
        type=str,
        help="Network interface to bind to (default: 'en0' for Mac Wi-Fi).",
    )
    parser.add_argument(
        "--debug",
        action="store_true",
        help="Verbose mode for debugging.",
    )
    parser.add_argument(
        "--to-mkv",
        action="store_true",
        help="Convert MP4 files with .srt into MKV with native SRT subtitles (Smart TV compatible).",
    )
    parser.add_argument(
        "--cast",
        action="store_true",
        help="Cast the movie directly to a Google Chromecast device instead of starting MiniDLNA.",
    )
    parser.add_argument(
        "--cast-device",
        "--device",
        "-d",
        dest="cast_device",
        type=str,
        default=None,
        help="Target Chromecast device name or IP (default: auto-detect).",
    )
    return parser.parse_args()


def has_subtitle_stream(video_file: Path) -> bool:
    """Check if video file already contains an embedded subtitle track."""
    ffprobe_bin = shutil.which("ffprobe")
    if not ffprobe_bin:
        return False
    try:
        cmd = [
            ffprobe_bin,
            "-v",
            "error",
            "-select_streams",
            "s",
            "-show_entries",
            "stream=index",
            "-of",
            "csv=p=0",
            str(video_file),
        ]
        res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
        return bool(res.stdout.strip())
    except Exception:
        return False


def convert_to_mkv_subtitles(target_target: Path) -> None:
    """
    Finds video files (MP4/M4V) that have a matching .srt subtitle and packages them
    into MKV with a native SRT subtitle track. Takes ~1-2s (stream copy, no re-encoding).
    If target_target is a single file, only converts that file.
    """
    ffmpeg_bin = shutil.which("ffmpeg")
    if not ffmpeg_bin:
        print("Warning: ffmpeg not found. Install with 'brew install ffmpeg' to use --to-mkv.", file=sys.stderr)
        return

    # Determine files to process
    if target_target.is_file():
        if target_target.suffix.lower() in {".mp4", ".m4v"}:
            video_files = [target_target]
        else:
            video_files = []
    else:
        video_files = [
            f for f in target_target.rglob("*")
            if f.is_file() and f.suffix.lower() in {".mp4", ".m4v"}
        ]

    for video in video_files:
        # Ignore files that were already generated by this script
        if video.name.startswith("+SUB_"):
            continue

        srt_file = video.with_suffix(".srt")
        if not srt_file.exists():
            continue

        # Prefix with +SUB_ so it sorts at the very top (ASCII 43 before numbers and letters)
        target_mkv = video.with_name(f"+SUB_{video.stem}.mkv")
        if target_mkv.exists() and has_subtitle_stream(target_mkv):
            # Already converted and contains subtitle track
            continue

        print(f"🔄 Packaging {video.name} + {srt_file.name} -> {target_mkv.name}...")
        temp_output = video.with_name(f".tmp_pkg_{target_mkv.name}")
        cmd = [
            ffmpeg_bin,
            "-y",
            "-i",
            str(video),
            "-i",
            str(srt_file),
            "-c",
            "copy",
            "-c:s",
            "ass",
            "-metadata:s:s:0",
            "language=eng",
            str(temp_output),
        ]

        try:
            res = subprocess.run(
                cmd,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.PIPE,
                text=True,
            )
            if res.returncode == 0 and temp_output.exists() and temp_output.stat().st_size > 0:
                temp_output.replace(target_mkv)
                print(f"✅ Created {target_mkv.name} with native SRT subtitles.")
            else:
                if temp_output.exists():
                    temp_output.unlink()
                print(f"⚠️  Could not convert {video.name}: {res.stderr.strip()[:120]}", file=sys.stderr)
        except Exception as e:
            if temp_output.exists():
                temp_output.unlink()
            print(f"⚠️  Error converting {video.name}: {e}", file=sys.stderr)


def discover_default_cast_device() -> str | None:
    """Attempts to find the default local Chromecast name using mDNS."""
    try:
        proc = subprocess.Popen(
            ["dns-sd", "-B", "_googlecast._tcp", "."],
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
        )
        import time
        time.sleep(1.0)
        proc.terminate()
        out, _ = proc.communicate()
        for line in out.splitlines():
            if "_googlecast._tcp." in line:
                instance = line.split("_googlecast._tcp.")[-1].strip()
                if instance:
                    # Resolve friendly name
                    l_proc = subprocess.Popen(
                        ["dns-sd", "-L", instance, "_googlecast._tcp", "local."],
                        stdout=subprocess.PIPE,
                        stderr=subprocess.DEVNULL,
                        text=True,
                    )
                    time.sleep(0.8)
                    l_proc.terminate()
                    l_out, _ = l_proc.communicate()
                    for l_line in l_out.splitlines():
                        if "fn=" in l_line:
                            for part in l_line.split():
                                if part.startswith("fn="):
                                    return part.split("fn=")[1]
    except Exception:
        pass
    return None


def cast_media(video_path: Path, device: str | None = None) -> None:
    """
    Casts a video file and its matching subtitles directly to a Google Chromecast
    using the 'catt' CLI module.
    """
    python_bin = sys.executable

    # Check if catt module is installed
    try:
        import catt  # noqa: F401
    except ImportError:
        print("Error: 'catt' is not installed. Install it with: pip3 install catt", file=sys.stderr)
        sys.exit(1)

    # Auto-detect target device name if not explicitly passed
    target_device = device
    if not target_device:
        detected = discover_default_cast_device()
        if detected:
            target_device = detected

    # Detect accompanying subtitles (.srt or .vtt)
    sub_file = None
    for ext in [".srt", ".vtt"]:
        candidate = video_path.with_suffix(ext)
        if candidate.exists():
            sub_file = candidate
            break

    # Build catt command
    cmd = [python_bin, "-m", "catt.cli"]
    if target_device:
        cmd.extend(["-d", target_device])

    cmd.append("cast")
    if sub_file:
        print(f"💬 Found subtitle track: {sub_file.name}")
        cmd.extend(["-s", str(sub_file)])

    cmd.append(str(video_path))

    target_desc = f"device '{target_device}'" if target_device else "Chromecast"
    print(f"🎬 Casting '{video_path.name}' to {target_desc}...")
    print("📺 Playback started! Use Ctrl+C to stop casting.\n")

    def send_chromecast_stop() -> None:
        """Sends an explicit stop signal to the Chromecast receiver so it does not buffer or spin."""
        stop_cmd = [python_bin, "-m", "catt.cli"]
        if target_device:
            stop_cmd.extend(["-d", target_device])
        stop_cmd.append("stop")
        try:
            subprocess.run(stop_cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=5)
        except Exception:
            pass

    try:
        # Run catt interactively so user can see progress and controls
        subprocess.run(cmd)
    except KeyboardInterrupt:
        print("\n🛑 Interrupt received! Stopping Chromecast receiver...")
    finally:
        send_chromecast_stop()
        print("✅ Chromecast session stopped.")


def main() -> None:
    args = parse_args()

    # 1. Validate and resolve target path (file or folder)
    input_path = Path(args.media).expanduser().resolve()
    if not input_path.exists():
        print(f"Error: '{input_path}' does not exist.", file=sys.stderr)
        sys.exit(1)

    # If --cast is selected, handle Chromecast streaming directly
    if args.cast:
        if input_path.is_dir():
            # Find first playable video file in directory
            valid_exts = {".mp4", ".mkv", ".m4v", ".webm", ".avi"}
            video_files = [f for f in input_path.rglob("*") if f.is_file() and f.suffix.lower() in valid_exts]
            if not video_files:
                print(f"Error: No video files found in '{input_path}'.", file=sys.stderr)
                sys.exit(1)
            target_video = video_files[0]
            print(f"Multiple files in folder. Selecting: {target_video.name}")
        else:
            target_video = input_path

        cast_media(target_video, device=args.cast_device)
        return

    # 2. DLNA Flow: Verify minidlnad is installed
    minidlna_bin = shutil.which("minidlnad")
    if not minidlna_bin:
        print("Error: 'minidlnad' not found. Install it with: brew install minidlna", file=sys.stderr)
        sys.exit(1)

    # If a specific file is provided, stream its parent folder
    if input_path.is_file():
        media_path = input_path.parent
        single_video = input_path
    else:
        media_path = input_path
        single_video = None

    # Safety guardrail: Prevent accidentally sharing your entire home directory or root
    forbidden_paths = {Path("/").resolve(), Path.home().resolve()}
    if media_path in forbidden_paths:
        print(f"Security Refusal: Sharing '{media_path}' exposes too many personal files.", file=sys.stderr)
        sys.exit(1)

    # 3. Optional pre-index conversion to MKV
    if args.to_mkv:
        convert_to_mkv_subtitles(single_video if single_video else media_path)

    # 4. Create a temporary directory that auto-deletes on exit
    with tempfile.TemporaryDirectory(prefix="watchtv_dlna_") as temp_dir:
        temp_path = Path(temp_dir)
        conf_file = temp_path / "minidlna.conf"
        db_dir = temp_path / "cache"
        log_dir = temp_path / "logs"
        db_dir.mkdir()
        log_dir.mkdir()

        # Generate a fresh, isolated config for this session only
        # Note: strict_dlna=no is critical for Smart TVs (Samsung, LG, Philips, etc.) to receive external subtitle tags
        config_content = f"""
network_interface={args.interface}
port=8200
media_dir=V,{media_path}
db_dir={db_dir}
log_dir={log_dir}
friendly_name={args.name}
inotify=yes
strict_dlna=no
notify_interval=60
"""
        conf_file.write_text(config_content.strip() + "\n", encoding="utf-8")

        print(f"🎬 Serving folder : {media_path}")
        print(f"📺 TV Server Name : {args.name}")
        print("🛑 Press Ctrl+C to stop streaming and wipe temporary cache...\n")

        # 4. Run minidlnad in foreground debug mode (-d) and force a fresh rescan (-R)
        cmd = [minidlna_bin, "-d", "-R", "-f", str(conf_file)]
        if args.debug:  # verbose mode for debugging
            process = subprocess.Popen(cmd)
        else:  # less verbose mode
            process = subprocess.Popen(
                cmd,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )

        try:
            process.wait()
        except KeyboardInterrupt:
            print("\nShutting down DLNA server...")
            process.terminate()
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                process.kill()
        finally:
            print("✅ Server stopped and temporary database cleaned up.")


if __name__ == "__main__":
    main()
